function getJacketForEra(era: EraTag, album: string): string {
  if (album.includes('Rejoice') || album.includes('ミックスナッツ'))
    return '/src/assets/images/album_art_rejoice_vibe_1793849695153.jpg';
  if (album.includes('Editorial') || album.includes('HELLO'))
    return '/src/assets/images/album_art_editorial_vibe_1793849696589.jpg';
  if (album.includes('Traveler') || album.includes('Stand By You'))
    return '/src/assets/images/album_art_traveler_vibe_1793854124340.jpg';
  if (era === 'latest_2025_2026')
    return '/src/assets/images/album_art_same_blue_vibe_1793854124064.jpg';
  if (album.includes('エスカパレード') || album.includes('Escaparade'))
    return '/src/assets/images/hero_magazine_collage_1793849692931.jpg';
  if (album.includes('レポート'))
    return '/src/assets/images/live_stadium_confetti_1793849699286.jpg';
  return '/src/assets/images/sacred_matsue_sunset_1793849698665.jpg';
}

